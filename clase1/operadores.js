//Aritmeticos
console.log(5 + 3) //suma
console.log(5 - 3) //resta
console.log(5 * 3) //multiplicacion
console.log(5 / 3) //division
console.log(5 % 3) //modulo
console.log(5 ** 3) //exponente

//Comparacion
console.log(5 > 3) //mayor que
console.log(5 < 3) //menor que
console.log(5 >= 3) //mayor o igual que
console.log(5 <= 3) //menor o igual que
console.log(5 === 3) //igual que
console.log(5 !== 3) //distinto que

//Logicos
console.log(5 > 3 && 5 < 10) //and
console.log(5 > 3 || 5 < 10) //or
console.log(!(5 > 3)) //not
//tabla de verdad
// A B A && B A || B !A